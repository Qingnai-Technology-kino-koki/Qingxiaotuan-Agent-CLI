#include <stdio.h>
#include <stdint.h>
#define main crypto_main
#include "crypto/crypto.c"
#undef main
int main(void){
    uint8_t key[32]={
      0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f,
      0x10,0x11,0x12,0x13,0x14,0x15,0x16,0x17,0x18,0x19,0x1a,0x1b,0x1c,0x1d,0x1e,0x1f};
    uint32_t rk[60]; aes_keyexp(key,rk);
    /* FIPS C.3 expected w[8]=0xa0fafe17, w[9]=0x88542cb1,... */
    printf("w[8]=%08x (exp a0fafe17)\n", rk[8]);
    printf("w[9]=%08x (exp 88542cb1)\n", rk[9]);
    printf("w[10]=%08x (exp 23a33939)\n", rk[10]);
    printf("w[14]=%08x (exp d251e1be)\n", rk[14]);
    return 0;
}
